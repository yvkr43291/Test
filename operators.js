// Arithmatic operator
let a = 10;
let b = 5;

console.log(a + b); // 15
console.log(a - b); // 5
console.log(a * b); // 50
console.log(a / b); // 2
console.log(a % b); // 0

// Assignment operators
let x = 10;

x += 5;
console.log(a); // 15

x -= 3;
console.log(a); // 12

x *= 2;
console.log(a); // 24

//comparision operators
let y = 10;
let z = 20;

console.log(y > z);  // false
console.log(y < z);  // true
console.log(y == 10); // true
console.log(y === "10"); // false

//Logical operator
let age = 25;

console.log(age > 18 && age < 60); // true

console.log(age < 18 || age > 20); // true

console.log(!(age > 18)); // false


